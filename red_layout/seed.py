def ensure_bays(db) -> None:
    existing = {bay.id: bay for bay in db.query(Bay).all()}
    changed = False
    for bay_id, zone, label in BAYS:
        bay = existing.get(bay_id)
        if bay is None:
            db.add(Bay(id=bay_id, zone=zone, label=label))
            changed = True
        elif bay.zone != zone or bay.label != label:
            bay.zone = zone
            bay.label = label
            changed = True
    if changed:
        db.commit()


def normalize_empty_labels(db) -> None:
    changed = False
    for machine in db.query(Machine).all():
        if (machine.area or "").upper() in {"VASCO", "VAZIO"}:
            if machine.area != "VAZIO":
                machine.area = "VAZIO"
                changed = True
        if (machine.user_name or "").strip().upper() in {"VASCO", "VAZIO"}:
            machine.user_name = ""
            changed = True
    if changed:
        db.commit()


def seed_if_empty(db) -> None:
    ensure_bays(db)

    if db.query(Machine).count() > 0:
        return

    for item in MACHINES:
        data = dict(item)
        bay_id = data.pop("bay_id", None)
        machine = Machine(**data)
        db.add(machine)
        db.flush()
        if bay_id:
            machine.bay_id = bay_id
    db.commit()
